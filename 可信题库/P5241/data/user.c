#include <stdlib.h>

/**
 * Note: The returned array must be malloced, assume caller calls free().
 */
int* finishTimes(int* arrival, int arrivalSize, int* duration, int durationSize,
                 int* priority, int prioritySize, int* returnSize) {
    (void)arrival; (void)arrivalSize; (void)duration; (void)durationSize;
    (void)priority; (void)prioritySize;
    *returnSize = 0;
    return NULL;
}
